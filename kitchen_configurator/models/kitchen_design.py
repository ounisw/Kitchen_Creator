import base64
import json
import math

from odoo import _, api, fields, models
from odoo.exceptions import UserError, ValidationError
from odoo.fields import Command

# Locales supported by the configurator (see src/i18n/messages.ts).
CONFIGURATOR_LOCALES = ('fr', 'en', 'ar')
# Snapshot schema version of the configurator (see src/services/projectStorage.ts).
SNAPSHOT_VERSION = 1
MAX_SNAPSHOT_SIZE = 5 * 1024 * 1024
MAX_QUOTE_LINES = 500
MAX_DRAWING_SIZE = 4 * 1024 * 1024
UNIT_UOM = {
    'u': 'uom.product_uom_unit',
    'm': 'uom.product_uom_meter',
    'm²': 'uom.product_uom_square_meter',
}


class KitchenDesign(models.Model):
    _name = 'kitchen.design'
    _description = "Kitchen 3D project"
    _inherit = ['mail.thread', 'mail.activity.mixin']
    _order = 'write_date desc, id desc'

    name = fields.Char(required=True, tracking=True, default=lambda self: _("New"))
    partner_id = fields.Many2one('res.partner', string="Customer", required=True, index=True, tracking=True)
    user_id = fields.Many2one(
        'res.users', string="Salesperson", index=True, tracking=True,
        domain="[('share', '=', False)]",
        default=lambda self: self.env.user if not self.env.user.share else False,
    )
    company_id = fields.Many2one('res.company', required=True, index=True, default=lambda self: self.env.company)
    sale_order_id = fields.Many2one('sale.order', string="Quotation", copy=False, tracking=True)
    sale_order_ids = fields.One2many('sale.order', 'kitchen_design_id', string="Quotations")
    sale_order_count = fields.Integer(compute='_compute_sale_order_count')
    project_type = fields.Selection([
        ('kitchen', "Kitchen"),
        ('wardrobe', "Wardrobe"),
    ], default='kitchen', required=True, tracking=True,
        help="Kitchen or wardrobe (dressing). Set when the project is saved from the configurator.")
    state = fields.Selection([
        ('draft', "Design"),
        ('requested', "Quote requested"),
        ('quoted', "Quoted"),
    ], default='draft', required=True, tracking=True)
    data = fields.Json(string="Configurator project", copy=True)
    last_saved = fields.Datetime(readonly=True, copy=False)
    # Technical drawing generated by the configurator (SVG views, cabinet schedule, labels).
    drawing = fields.Json(string="Technical drawing", copy=False)
    has_drawing = fields.Boolean(compute='_compute_has_drawing')
    has_design = fields.Boolean(compute='_compute_has_design')

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if not vals.get('name') or vals['name'] == _("New"):
                vals['name'] = self.env['ir.sequence'].sudo().next_by_code('kitchen.design') or _("New")
        return super().create(vals_list)

    @api.depends('sale_order_ids')
    def _compute_sale_order_count(self):
        for design in self:
            design.sale_order_count = len(design.sale_order_ids)

    @api.depends('drawing')
    def _compute_has_drawing(self):
        for design in self:
            design.has_drawing = bool(design.drawing)

    @api.depends('data')
    def _compute_has_design(self):
        for design in self:
            design.has_design = bool(design.data)

    # ------------------------------------------------------------------
    # Actions
    # ------------------------------------------------------------------

    def action_open_configurator(self):
        self.ensure_one()
        return {'type': 'ir.actions.act_url', 'url': f'/kitchen/configurator/{self.id}', 'target': 'new'}

    def action_view_sale_orders(self):
        self.ensure_one()
        action = self.env['ir.actions.act_window']._for_xml_id('sale.action_quotations_with_onboarding')
        action['domain'] = [('kitchen_design_id', '=', self.id)]
        action['context'] = {'default_kitchen_design_id': self.id, 'default_partner_id': self.partner_id.id}
        if self.sale_order_count == 1:
            action.update(views=[(False, 'form')], res_id=self.sale_order_ids.id)
        return action

    # ------------------------------------------------------------------
    # Configurator host page
    # ------------------------------------------------------------------

    def _configurator_locale(self):
        lang = (self.env.user.lang or '').split('_')[0]
        return lang if lang in CONFIGURATOR_LOCALES else None

    def _configurator_config(self, audience):
        """Configuration injected in the configurator page (window.__KITCHEN_CONFIG__)."""
        self.ensure_one()
        if audience == 'portal':
            back_url = '/my/kitchen'
        elif self.sale_order_id:
            back_url = f'/odoo/sales/{self.sale_order_id.id}'
        else:
            back_url = f'/odoo/kitchen-projects/{self.id}'
        title = self.name
        if audience == 'sales' and self.sale_order_id:
            title = f'{self.name} · {self.sale_order_id.name}'
        return {
            'backend': 'odoo',
            'audience': audience,
            'projectId': self.id,
            'title': f'{title} — {self.partner_id.display_name}',
            'apiBase': '/kitchen/api',
            'backUrl': back_url,
            'locale': self._configurator_locale(),
            'projectType': self.project_type,
            'project': self.data or None,
        }

    # ------------------------------------------------------------------
    # Save / quote (called by the controller after the access check)
    # ------------------------------------------------------------------

    @api.model
    def _validate_snapshot(self, data):
        if not isinstance(data, dict) or data.get('version') != SNAPSHOT_VERSION \
                or not isinstance(data.get('kitchen'), dict) or not isinstance(data.get('room'), dict):
            raise ValidationError(_("Invalid kitchen project."))
        if len(json.dumps(data)) > MAX_SNAPSHOT_SIZE:
            raise ValidationError(_("The kitchen project is too large."))
        return data

    @api.model
    def _validate_drawing(self, drawing):
        """Technical drawing from the configurator; None when missing or malformed (never blocks a save)."""
        if not isinstance(drawing, dict) or len(json.dumps(drawing)) > MAX_DRAWING_SIZE:
            return None
        plan, elevations = drawing.get('plan'), drawing.get('elevations')
        rows, worktops, labels = drawing.get('rows'), drawing.get('worktops') or [], drawing.get('labels')
        if not isinstance(plan, str) or not isinstance(elevations, list) or not isinstance(rows, list) \
                or not isinstance(worktops, list) or not isinstance(labels, dict):
            return None
        svgs = [plan] + [e.get('svg') for e in elevations if isinstance(e, dict)]
        if len(svgs) != len(elevations) + 1 or not all(isinstance(v, str) and v.lstrip().startswith('<svg') for v in svgs):
            return None
        text = lambda value: str(value)[:1000] if isinstance(value, (str, int, float)) else ''
        return {
            'plan': plan,
            'elevations': [{'title': text(e.get('title')), 'svg': e['svg']} for e in elevations],
            'rows': [{k: text(r.get(k)) for k in ('mark', 'name', 'wall', 'offset', 'elevation', 'width', 'height', 'depth', 'detail')}
                     for r in rows if isinstance(r, dict)],
            'worktops': [{k: text(w.get(k)) for k in ('wall', 'start', 'end', 'length', 'depth', 'thickness', 'cutouts')}
                         for w in worktops if isinstance(w, dict)],
            'labels': {text(k): text(v) for k, v in labels.items()},
        }

    def _save_snapshot(self, data, drawing=None):
        self.ensure_one()
        data = self._validate_snapshot(data)
        vals = {'data': data, 'last_saved': fields.Datetime.now()}
        if data['kitchen'].get('projectType') in ('kitchen', 'wardrobe'):
            vals['project_type'] = data['kitchen']['projectType']
        if drawing is not None:
            vals['drawing'] = self._validate_drawing(drawing)
        self.write(vals)

    def _drawing_report_values(self):
        """Views of the technical drawing as images for the PDF report. The SVGs are
        embedded as <img> data URIs: whatever they contain, no script can run."""
        self.ensure_one()
        drawing = self.drawing or {}
        src = lambda svg: 'data:image/svg+xml;base64,' + base64.b64encode(svg.encode()).decode()
        labels = drawing.get('labels') or {}
        views = []
        if drawing.get('plan'):
            views.append({'title': labels.get('topView', _("Top view")), 'src': src(drawing['plan'])})
        views += [{'title': e['title'], 'src': src(e['svg'])} for e in drawing.get('elevations', [])]
        rows = drawing.get('rows', [])
        return {
            'views': views,
            'rows': rows,
            'worktops': drawing.get('worktops', []),
            'labels': labels,
            # Wardrobes: configuration column in the schedule, infill legend under the front views.
            'has_detail': any(row.get('detail') for row in rows),
        }

    def action_print_drawing(self):
        self.ensure_one()
        if not self.drawing:
            raise UserError(_("No technical drawing yet: open the kitchen configurator and save the project."))
        return self.env.ref('kitchen_configurator.action_report_kitchen_drawing').report_action(self)

    @api.model
    def _validate_quote_lines(self, lines):
        if not isinstance(lines, list) or not lines:
            raise ValidationError(_("The quote is empty."))
        if len(lines) > MAX_QUOTE_LINES:
            raise ValidationError(_("Too many quote lines."))
        result = []
        for line in lines:
            if not isinstance(line, dict):
                raise ValidationError(_("Invalid quote line."))
            ref, name = line.get('ref'), line.get('name')
            quantity, price = line.get('quantity'), line.get('priceUnit')
            if not isinstance(ref, str) or not ref.strip() or len(ref) > 128 or not isinstance(name, str):
                raise ValidationError(_("Invalid quote line."))
            if not all(isinstance(v, (int, float)) and not isinstance(v, bool) and math.isfinite(v) for v in (quantity, price)) \
                    or quantity <= 0 or price < 0:
                raise ValidationError(_("Invalid quantity or price on line %s.", name))
            product_name = line.get('productName')
            result.append({
                'ref': ref.strip(),
                'product_name': (product_name if isinstance(product_name, str) and product_name.strip() else name)[:256],
                'name': name[:2000],
                'quantity': quantity,
                'unit': line.get('unit') if line.get('unit') in UNIT_UOM else 'u',
                'price_unit': price,
            })
        return result

    def _kitchen_products(self, lines, create_missing):
        """Products by configurator reference. Missing ones are created (sales users)
        or replaced by the generic "Kitchen item" product (portal requests)."""
        self.ensure_one()
        Product = self.env['product.product'].sudo().with_company(self.company_id)
        refs = {line['ref'] for line in lines}
        products = {}
        for product in Product.search([
            ('kitchen_ref', 'in', list(refs)),
            ('company_id', 'in', [False, self.company_id.id]),
        ], order='company_id, id'):
            products.setdefault(product.kitchen_ref, product)
        fallback = self.env.ref('kitchen_configurator.product_kitchen_item').sudo()
        category = self.env.ref('kitchen_configurator.product_category_kitchen', raise_if_not_found=False)
        for line in lines:
            ref = line['ref']
            if ref in products:
                continue
            if not create_missing:
                products[ref] = fallback
                continue
            uom = self.env.ref(UNIT_UOM[line['unit']], raise_if_not_found=False)
            vals = {
                'name': line['product_name'],
                'kitchen_ref': ref,
                'type': 'consu',
                'sale_ok': True,
                'list_price': line['price_unit'],
            }
            if category:
                vals['categ_id'] = category.id
            if uom:
                vals['uom_id'] = uom.id
            products[ref] = Product.create(vals)
        return products

    def _quote_order(self, portal):
        """Quotation to fill: the linked one while it is still a quotation, a new one otherwise."""
        self.ensure_one()
        order = self.sale_order_id
        if order and order.state in ('draft', 'sent'):
            return order.sudo() if portal else order
        partner = self.partner_id
        salesperson = self.user_id or partner.commercial_partner_id.user_id
        SaleOrder = self.env['sale.order'].sudo() if portal else self.env['sale.order']
        order = SaleOrder.with_company(self.company_id).create({
            'partner_id': partner.id,
            'company_id': self.company_id.id,
            'user_id': salesperson.id or False,
            'kitchen_design_id': self.id,
            'origin': self.name,
        })
        self.sudo().sale_order_id = order.id
        return order

    def _apply_quote(self, lines, data, portal=False, drawing=None):
        """Creates or updates the quotation from the configurator lines.

        Lines previously generated by the configurator are replaced; lines added
        by hand are kept. A confirmed order is never modified.
        """
        self.ensure_one()
        lines = self._validate_quote_lines(lines)
        self._save_snapshot(data, drawing)
        products = self._kitchen_products(lines, create_missing=not portal)
        order = self._quote_order(portal)
        commands = [Command.unlink(line.id) for line in order.order_line if line.kitchen_generated]
        sequence = 1000
        section = (_("Wardrobe — %s", self.name) if self.project_type == 'wardrobe' else _("Kitchen — %s", self.name))
        if portal:
            section = _("%s (customer request: prices to be checked)", section)
        commands.append(Command.create({
            'display_type': 'line_section', 'name': section, 'sequence': sequence, 'kitchen_generated': True,
        }))
        for line in lines:
            sequence += 1
            commands.append(Command.create({
                'product_id': products[line['ref']].id,
                'name': line['name'],
                'product_uom_qty': line['quantity'],
                'price_unit': line['price_unit'],
                'sequence': sequence,
                'kitchen_generated': True,
            }))
        order.write({'order_line': commands})

        if portal:
            self.sudo().state = 'requested'
            body = _("Quote request sent by the customer from the 3D kitchen configurator. Please check the prices.")
            order.message_post(body=body)
            if order.user_id:
                order.activity_schedule(
                    'mail.mail_activity_data_todo',
                    summary=_("Check the kitchen quote request"),
                    note=body,
                    user_id=order.user_id.id,
                )
            url = '/my/kitchen'
        else:
            self.state = 'quoted'
            url = f'/odoo/sales/{order.id}'
        return {'name': order.name, 'url': url}

    @api.model
    def _create_portal_design(self, name=None, project_type='kitchen'):
        """Project created by a portal customer from /my/kitchen."""
        partner = self.env.user.partner_id
        if not self.env.user._is_portal():
            raise UserError(_("Only portal users can create kitchen projects from the portal."))
        return self.sudo().create({
            'name': (name or '').strip()[:128] or _("New"),
            'project_type': project_type if project_type in ('kitchen', 'wardrobe') else 'kitchen',
            'partner_id': partner.id,
            'user_id': partner.commercial_partner_id.user_id.id or partner.user_id.id or False,
            'company_id': (partner.company_id or self.env.user.company_id).id,
        })
