from odoo import _, fields, models
from odoo.exceptions import UserError


class SaleOrder(models.Model):
    _inherit = 'sale.order'

    kitchen_design_id = fields.Many2one('kitchen.design', string="Kitchen 3D project", copy=False, index='btree_not_null')
    kitchen_has_drawing = fields.Boolean(related='kitchen_design_id.has_drawing')

    def action_open_kitchen_configurator(self):
        self.ensure_one()
        if self.state not in ('draft', 'sent'):
            raise UserError(_("Only quotations can be edited with the kitchen configurator."))
        design = self.kitchen_design_id
        if not design:
            design = self.env['kitchen.design'].create({
                'partner_id': self.partner_id.id,
                'user_id': (self.user_id or self.env.user).id,
                'company_id': self.company_id.id,
                'sale_order_id': self.id,
            })
            self.kitchen_design_id = design
        return design.action_open_configurator()

    def action_print_kitchen_drawing(self):
        self.ensure_one()
        return self.kitchen_design_id.action_print_drawing()

    def action_view_kitchen_design(self):
        self.ensure_one()
        return {
            'type': 'ir.actions.act_window',
            'res_model': 'kitchen.design',
            'res_id': self.kitchen_design_id.id,
            'view_mode': 'form',
        }


class SaleOrderLine(models.Model):
    _inherit = 'sale.order.line'

    kitchen_generated = fields.Boolean(
        string="Generated by the kitchen configurator",
        copy=False,
        help="Replaced each time the quote is sent from the configurator. Lines added by hand are kept.",
    )
